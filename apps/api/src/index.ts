/**
 * Le Worker Cloudflare de la plateforme.
 *
 * Il ne contient aucune logique métier : il monte les routes de chaque module, et c'est tout.
 * **Ajouter un module, c'est ajouter une ligne ici.**
 *
 * Les fichiers de l'interface Angular ne passent pas par ce code : `wrangler.jsonc` les sert
 * directement depuis le stockage d'assets, et `run_worker_first` réserve `/api/*` au Worker.
 * Un seul déploiement, une seule origine — donc aucun CORS à configurer.
 */

import { routesProfile } from '@ns-studio/profile-api';
import { type ErreurApi } from '@ns-studio/profile-contract';
import { Hono } from 'hono';
import { secureHeaders } from 'hono/secure-headers';

const app = new Hono();

/**
 * Les en-têtes de sécurité des réponses de l'API.
 *
 * Le fichier `apps/web/public/_headers` ne les couvre pas : la documentation Cloudflare est
 * explicite — « custom headers defined in the `_headers` file are not applied to responses
 * generated by your Worker code ». Les pages et les assets passent donc par `_headers`, les
 * réponses de ce code par ce middleware, et `apps/api/test/en-tetes.test.ts` vérifie que les
 * deux déclarations n'ont pas divergé.
 *
 * `strictTransportSecurity` est désactivé **délibérément** : c'est le seul en-tête dont l'effet
 * survive à son retrait — un navigateur le mémorise, ici 180 jours. Le poser avant que le nom
 * de domaine définitif soit arrêté engage une adresse qu'on ne pourra pas reprendre. Phase 1.
 *
 * La CSP est en `Report-Only` : elle signale sans bloquer. Les styles de composant qu'Angular
 * injecte en `<style>` exigent `'unsafe-inline'` dans `style-src` ; le passage en mode appliqué
 * attend un nonce ou l'extraction de ces styles, en Phase 1.
 */
app.use(
  '/api/*',
  secureHeaders({
    // Même ordre et mêmes valeurs que dans `_headers` : les deux chaînes doivent être égales.
    contentSecurityPolicyReportOnly: {
      defaultSrc: ["'self'"],
      baseUri: ["'self'"],
      objectSrc: ["'none'"],
      scriptSrc: ["'self'"],
      styleSrc: ["'self'", "'unsafe-inline'"],
      imgSrc: ["'self'", 'data:'],
      fontSrc: ["'self'"],
      connectSrc: ["'self'"],
      frameSrc: ["'self'"],
      frameAncestors: ["'self'"],
      formAction: ["'self'"],
    },
    permissionsPolicy: {
      accelerometer: [],
      autoplay: [],
      camera: [],
      displayCapture: [],
      encryptedMedia: [],
      geolocation: [],
      gyroscope: [],
      magnetometer: [],
      microphone: [],
      midi: [],
      payment: [],
      usb: [],
      xrSpatialTracking: [],
    },
    // Le défaut de Hono est `no-referrer` ; on aligne sur `_headers`.
    referrerPolicy: 'strict-origin-when-cross-origin',
    strictTransportSecurity: false,
  }),
);

app.route('/api/profile', routesProfile);

/**
 * Filet pour les routes d'API inconnues.
 *
 * Sans lui, une faute de frappe sur `/api/…` renverrait la coquille Angular en HTML, et le
 * client échouerait à l'analyser avec un message incompréhensible.
 *
 * Le corps est annoté `ErreurApi` : les deux erreurs de l'API — contenu invalide et route
 * inconnue — passent ainsi par le même type, vérifié à la compilation. La réponse envoyée est
 * exactement celle d'avant.
 */
app.notFound((c) => {
  const corps: ErreurApi = { code: 'ROUTE_INCONNUE', message: `Aucune route ${c.req.path}.` };
  return c.json(corps, 404);
});

export default app;
